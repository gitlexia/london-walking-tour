export function photoUrl(key, width = 480) {
  const photo = PHOTOS[key];
  if (!photo) return '';
  const file = encodeURIComponent(photo.filename.replaceAll(' ', '_'));
  // Commons Special:FilePath returns a size-optimised thumbnail when `width` is present.
  return `https://commons.wikimedia.org/wiki/Special:FilePath/${file}?width=${width}`;
}

export function photoSourceUrl(key) {
  const photo = PHOTOS[key];
  return photo ? `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(photo.filename.replaceAll(' ', '_'))}` : '';
}

export function placePhotoKey(place) {
  return PHOTO_FOR_PLACE[place.id] || 'bigben';
}
